// Builds docs/code-map.md: what each file is, who requires whom (Mermaid graph), and the API routes. Run: node scripts/code-map.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const rel = (p) => path.relative(root, p).split(path.sep).join('/');
const list = (d, re) => (fs.existsSync(path.join(root, d)) ? fs.readdirSync(path.join(root, d)).filter((f) => re.test(f)).map((f) => d + '/' + f) : []);
const files = [...list('api', /\.js$/), 'server.js', ...list('lib', /\.js$/), ...list('public', /\.js$/), 'public/index.html'];
const first = (src) => { const m = src.split('\n').slice(0, 6).find((l) => /^\s*(\/\/|\/\*\*?|<!--)\s*\S/.test(l)); return m ? m.replace(/^\s*(\/\/|\/\*\*?|<!--)\s*/, '').replace(/\s*(-->|\*\/)\s*$/, '').slice(0, 130) : ''; };
const edges = [], info = {};
for (const f of files) {
  const src = fs.readFileSync(path.join(root, f), 'utf8');
  info[f] = { lines: src.split('\n').length, about: first(src) };
  if (f.endsWith('.html')) { for (const m of src.matchAll(/<script[^>]*\ssrc="([^"]+\.js)"/g)) { const t = 'public/' + m[1].replace(/^\//, ''); if (files.includes(t)) edges.push([f, t]); } continue; }
  for (const m of src.matchAll(/require\(\s*['"](\.[^'"]+)['"]\s*\)/g)) {
    let t = rel(path.resolve(path.dirname(path.join(root, f)), m[1]));
    if (!/\.\w+$/.test(t)) t += '.js';
    if (files.includes(t)) edges.push([f, t]);
  }
}
const id = (f) => f.replace(/[^A-Za-z0-9]/g, '_');
const group = (f) => (f.startsWith('api/') || f === 'server.js' ? 'Entry points' : f.startsWith('lib/') ? 'Server (lib)' : 'Browser (public)');
let md = '# Code map\n\nGenerated by `node scripts/code-map.js`. Arrows mean "requires" (or "loads with a script tag").\n\n```mermaid\nflowchart LR\n';
for (const g of ['Entry points', 'Server (lib)', 'Browser (public)']) {
  md += `  subgraph "${g}"\n`;
  for (const f of files.filter((x) => group(x) === g)) md += `    ${id(f)}["${f.split('/').pop()}"]\n`;
  md += '  end\n';
}
for (const [a, b] of edges) md += `  ${id(a)} --> ${id(b)}\n`;
md += '```\n\n## Files\n\n| File | Lines | What it is |\n|---|---|---|\n';
for (const f of files) md += `| \`${f}\` | ${info[f].lines} | ${info[f].about.replace(/\|/g, '/')} |\n`;
// API routes: handlers declared as `  async name(req` inside lib/app.js
const app = fs.readFileSync(path.join(root, 'lib/app.js'), 'utf8');
const routes = [...app.matchAll(/^  async ([a-z_0-9]+)\(req/gm)].map((m) => m[1]);
const by = {}; for (const r of routes) { const k = r.split('_')[0]; (by[k] = by[k] || []).push(r); }
md += `\n## API routes (${routes.length}, all in lib/app.js, called as POST /api?r=<name>)\n\n`;
for (const [k, v] of Object.entries(by).sort((a, b) => b[1].length - a[1].length)) md += `- **${k}** (${v.length}): ${v.map((x) => '`' + x + '`').join(', ')}\n`;
const tests = list('scripts', /^test-.*\.js$/);
md += `\n## Tests (${tests.length})\n\n${tests.map((t) => '`' + t.split('/').pop() + '`').join(', ')}\n`;
fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs', 'code-map.md'), md);
console.log(`${files.length} files, ${edges.length} links, ${routes.length} routes -> docs/code-map.md`);
