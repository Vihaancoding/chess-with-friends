// Builds public/openings.js from the Lichess opening list (https://github.com/lichess-org/chess-openings, CC0).
// Run: node scripts/build-openings.js            (downloads a.tsv … e.tsv)
//  or: node scripts/build-openings.js <dir>      (reads a.tsv … e.tsv from <dir>)
// Output: one line per opening, "ECO<TAB>Name<TAB>uci uci …", which the client replays to index positions.
const fs = require('fs');
const path = require('path');
const C = require('../public/chess.js');

const SRC = 'https://raw.githubusercontent.com/lichess-org/chess-openings/master/';
const sqIdx = (s) => 'abcdefgh'.indexOf(s[0]) + (8 - +s[1]) * 8;

// SAN ("Nbd7", "exd5", "O-O", "e8=Q+") -> legal move in this position
function fromSan(st, san) {
  const s = san.replace(/[+#!?]/g, '');
  const moves = C.legalMoves(st);
  if (s === 'O-O' || s === 'O-O-O') return moves.find((m) => m.castle === (s === 'O-O' ? 'K' : 'Q'));
  const mt = /^([NBRQK])?([a-h])?([1-8])?x?([a-h][1-8])(?:=([NBRQ]))?$/.exec(s);
  if (!mt) return null;
  const [, pc = 'P', ff, fr, to, promo] = mt;
  const hits = moves.filter((m) => {
    const from = C.sqName(m.from);
    return st.board[m.from][1] === pc && m.to === sqIdx(to) && (m.promo || undefined) === promo &&
      (!ff || from[0] === ff) && (!fr || from[1] === fr);
  });
  return hits.length === 1 ? hits[0] : null;
}

async function main() {
  const dir = process.argv[2];
  const rows = [];
  for (const f of ['a', 'b', 'c', 'd', 'e']) {
    const text = dir ? fs.readFileSync(path.join(dir, f + '.tsv'), 'utf8') : await (await fetch(SRC + f + '.tsv')).text();
    for (const line of text.split('\n').slice(1)) {
      if (!line.trim()) continue;
      const [eco, name, pgn] = line.split('\t');
      let st = C.initial();
      const uci = [];
      for (const tok of pgn.trim().split(/\s+/)) {
        if (/^\d+\.+$/.test(tok)) continue;
        const m = fromSan(st, tok);
        if (!m) throw new Error(`${eco} ${name}: cannot play ${tok}`);
        uci.push(C.sqName(m.from) + C.sqName(m.to) + (m.promo ? m.promo.toLowerCase() : ''));
        st = C.apply(st, m);
      }
      rows.push([eco, name, uci.join(' ')].join('\t'));
    }
  }
  const out = '// Generated by scripts/build-openings.js from the Lichess opening list (CC0). Do not edit by hand.\n' +
    '// One opening per line: ECO, name, moves in UCI.\n' +
    `(typeof self !== 'undefined' ? self : this).OPENINGS_TSV = ${JSON.stringify(rows.join('\n'))};\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'public', 'openings.js'), out);
  console.log(`Wrote ${rows.length} openings (${(out.length / 1024).toFixed(0)} KB)`);
}
main().catch((e) => { console.error(e.message); process.exit(1); });
